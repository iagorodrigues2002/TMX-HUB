import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const apiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function assertTrafficEntrypoints(pkg, docker) {
  if (
    !pkg.scripts?.start?.includes('node scripts/traffic-sync-server.mjs') ||
    !docker.includes('exec node scripts/traffic-sync-server.mjs')
  )
    throw Error('API production entrypoints must preserve the traffic synchronizer.');
}
export async function buildTrafficReader(
  output = join(apiRoot, 'scripts/traffic-meta-reader.mjs'),
) {
  const [pkg, docker] = await Promise.all([
    readFile(join(apiRoot, 'package.json'), 'utf8'),
    readFile(join(apiRoot, 'Dockerfile'), 'utf8'),
    readFile(join(apiRoot, 'scripts/traffic-sync-server.mjs'), 'utf8'),
  ]);
  assertTrafficEntrypoints(JSON.parse(pkg), docker);
  const source = await readFile(join(apiRoot, 'src/services/meta-traffic-reader.ts'), 'utf8');
  const result = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  });
  if (result.diagnostics?.some((item) => item.category === ts.DiagnosticCategory.Error))
    throw Error('Meta traffic reader compilation failed.');
  await mkdir(dirname(output), { recursive: true });
  await writeFile(
    output,
    `// Generated by the API build; no credentials are included.\n${result.outputText}`,
  );
  const alerts = await readFile(join(apiRoot, 'src/services/meta-traffic-alerts.ts'), 'utf8');
  const compiledAlerts = ts.transpileModule(alerts, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  });
  await writeFile(join(dirname(output), 'traffic-meta-alerts.mjs'), compiledAlerts.outputText);
  const require = createRequire(import.meta.url);
  const { build } = createRequire(require.resolve('tsup'))('esbuild');
  await build({
    entryPoints: [join(apiRoot, 'src/lib/secret-box.ts')],
    outfile: join(dirname(output), 'traffic-secret-box.mjs'),
    bundle: true, platform: 'node', format: 'esm', target: 'node22',
  });
  await build({
    entryPoints: [join(apiRoot, 'src/services/traffic-daily-store.ts')],
    outfile: join(dirname(output), 'traffic-daily-store.mjs'),
    bundle: true, platform: 'node', format: 'esm', target: 'node22',
    external: ['postgres'],
  });
  await build({
    entryPoints: [join(apiRoot, 'src/services/traffic-attribution.ts')],
    outfile: join(dirname(output), 'traffic-attribution-reader.cjs'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    minify: true,
    external: ['postgres', 'zod', 'pino'],
  });
  return output;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await buildTrafficReader();
